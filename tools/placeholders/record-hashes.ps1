# Writes assets/placeholders.json: the SHA-1 of every placeholder PNG / WAV under assets/.
# GENERATOR USE ONLY (tools/make-placeholders.ps1 calls it right after writing the placeholders).
#   -Since <time>   only files written at or after that time are (re)recorded; every other entry is kept as it was and files that were never
#                   recorded are skipped. So re-running the generator after you saved your own files can never turn them into "placeholders".
# Without -Since every PNG / WAV under assets/ is recorded - only do that on a tree that holds nothing but placeholders.
param([datetime]$Since = [datetime]::MinValue)
$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent (Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path))
$assets = Join-Path $repo 'assets'
$file = Join-Path $assets 'placeholders.json'
$sha = [Security.Cryptography.SHA1]::Create()
$base = (Resolve-Path $assets).Path.TrimEnd('\') + '\'
$map = @{}
if (Test-Path $file) { foreach ($p in ([IO.File]::ReadAllText($file) | ConvertFrom-Json).files.PSObject.Properties) { $map[$p.Name] = $p.Value } }
$n = 0
foreach ($f in Get-ChildItem $assets -Recurse -File) {
  if ($f.Extension -notmatch '^\.(png|wav)$') { continue }
  if ($f.LastWriteTime -lt $Since) { continue }
  $rel = $f.FullName.Substring($base.Length).Replace('\', '/')
  $map[$rel] = ([BitConverter]::ToString($sha.ComputeHash([IO.File]::ReadAllBytes($f.FullName))) -replace '-', '').ToLower()
  $n++
}
# entries whose file is gone are dropped
foreach ($k in @($map.Keys)) { if (-not (Test-Path (Join-Path $assets $k))) { $map.Remove($k) } }
$keys = New-Object 'Collections.Generic.List[string]'; $keys.AddRange([string[]]@($map.Keys)); $keys.Sort([StringComparer]::Ordinal)
$sb = New-Object Text.StringBuilder
[void]$sb.Append("{`n  `"note`": `"SHA-1 of every placeholder file exactly as generated by tools/make-placeholders.ps1. A file under assets/ whose hash still equals its entry is a placeholder: tools/scan-assets.ps1 never lists it and the game never loads it. Do not edit by hand.`",`n  `"algo`": `"sha1`",`n  `"files`": {`n")
for ($i = 0; $i -lt $keys.Count; $i++) { [void]$sb.Append('    "' + $keys[$i] + '": "' + $map[$keys[$i]] + '"' + $(if ($i -lt $keys.Count - 1) { ',' } else { '' }) + "`n") }
[void]$sb.Append("  }`n}`n")
[IO.File]::WriteAllText($file, $sb.ToString(), (New-Object Text.UTF8Encoding $false))
Write-Host "assets/placeholders.json: $($keys.Count) placeholders ($n hashed now)"
